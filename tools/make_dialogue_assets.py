FONT_CHARS = " ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.,!?:;'\"-+/()%ÁÀÂÃÉÊÍÓÔÕÚÜÇ"
CELL_W, CELL_H, COLS = 6, 9, 16
font = Image.new("RGBA", (COLS * CELL_W, ceil(len(FONT_CHARS) / COLS) * CELL_H))
for index, char in enumerate(FONT_CHARS):
    base = {"Á": "A", "À": "A", "Â": "A", "Ã": "A", "É": "E", "Ê": "E",
            "Í": "I", "Ó": "O", "Ô": "O", "Õ": "O", "Ú": "U", "Ü": "U", "Ç": "C"}.get(char, char)
    pattern = GLYPHS[base]
    x0, y0 = (index % COLS) * CELL_W, (index // COLS) * CELL_H
    for y, row in enumerate(pattern):
        for x, bit in enumerate(row):
            if bit == "1":
                font.putpixel((x0 + x, y0 + y + 1), (255, 255, 255, 255))
    if char in "ÁÉÍÓÚ":
        for dx in (2, 3): font.putpixel((x0 + dx, y0), (255, 255, 255, 255))
    elif char in "À":
        for dx in (1, 2): font.putpixel((x0 + dx, y0), (255, 255, 255, 255))
    elif char in "ÂÊÔ":
        for dx in (1, 3): font.putpixel((x0 + dx, y0), (255, 255, 255, 255))
    elif char in "ÃÕ":
        for dx in (0, 2, 4): font.putpixel((x0 + dx, y0), (255, 255, 255, 255))
    elif char == "Ü":
        for dx in (1, 3): font.putpixel((x0 + dx, y0), (255, 255, 255, 255))
    elif char == "Ç":
        font.putpixel((x0 + 2, y0 + 8), (255, 255, 255, 255))
font.save(OUT / "font.png")
(OUT / "font.json").write_text(json.dumps({"chars": FONT_CHARS, "cellW": CELL_W,
                                           "cellH": CELL_H, "cols": COLS}, ensure_ascii=False), encoding="utf-8")

